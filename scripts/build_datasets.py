def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (dt.datetime,)):
        return "'" + v.strftime("%Y-%m-%d %H:%M:%S") + "'"
    if isinstance(v, dt.date):
        return "'" + v.isoformat() + "'"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return "%.2f" % v
    return "'" + str(v).replace("'", "''") + "'"


class DS:
    def __init__(self, id_, title, desc, seed):
        self.id, self.title, self.desc = id_, title, desc
        self.r = random.Random(seed)
        self.ddl, self.inserts, self.tables, self.rows, self.edge = [], [], [], 0, []

    def table(self, name, ddl):
        self.tables.append(name)
        self.ddl.append("CREATE TABLE %s (\n  %s\n);" % (name, ",\n  ".join(ddl)))

    def insert(self, name, cols, rows):
        self.rows += len(rows)
        for i in range(0, len(rows), 200):
            chunk = rows[i:i + 200]
            vals = ",\n".join("(" + ", ".join(lit(v) for v in row) + ")" for row in chunk)
            self.inserts.append("INSERT INTO %s (%s) VALUES\n%s;" % (name, ", ".join(cols), vals))

    def date(self, a=START, b=END):
        return a + dt.timedelta(days=self.r.randint(0, (b - a).days))

    def ts(self, a=START, b=END):
        d = self.date(a, b)
        return dt.datetime(d.year, d.month, d.day, self.r.randint(7, 22), self.r.randint(0, 59), self.r.randint(0, 59))

    def name(self):
        return self.r.choice(FIRST), self.r.choice(LAST)

    def write(self):
        head = "-- %s dataset (generated by scripts/build_datasets.py; do not edit by hand)\n" % self.title
        drops = "\n".join("DROP TABLE IF EXISTS %s CASCADE;" % t for t in reversed(self.tables))
        body = head + drops + "\n\n" + "\n\n".join(self.ddl) + "\n\n" + "\n\n".join(self.inserts) + "\n"
        with open(os.path.join(OUT, self.id + ".sql"), "w") as f:
            f.write(body)
        assert len(self.desc) <= 160, self.id
        return {"id": self.id, "title": self.title, "description": self.desc, "tables": self.tables,
                "rows": self.rows, "edgeCases": self.edge}


def email(first, last, n, domain):
    return ("%s.%s%d@%s" % (first, last, n, domain)).lower().replace("'", "")


