/**
 * Data Visualization Explorer engine: a fixed sales fixture, aggregation, and the data behind each chart type. Pure and
 * deterministic. `adviseChart` gives rule-based guidance on when a chart fits and when it can mislead; the rules are
 * written out below, not guessed.
 */
export interface SaleRow { month: string; region: string; category: string; channel: string; units: number; price: number; revenue: number }

const REGIONS = ["North", "South", "East", "West"], CATEGORIES = ["Laptops", "Phones", "Audio"], CHANNELS = ["Online", "Store"];
const MONTHS = ["2025-01", "2025-02", "2025-03", "2025-04", "2025-05", "2025-06"];
const BASE: Record<string, number> = { Laptops: 900, Phones: 600, Audio: 120 };

/** 6 months × 4 regions × 3 categories × 2 channels = 144 rows, generated by a fixed formula (no randomness). */
export const SALES: SaleRow[] = MONTHS.flatMap((month, m) => REGIONS.flatMap((region, r) => CATEGORIES.flatMap((category, c) => CHANNELS.map((channel, ch) => {
  const units = 4 + ((m * 3 + r * 5 + c * 7 + ch * 2) % 9) + (category === "Audio" ? 6 : 0) + (month === "2025-04" ? 3 : 0);
  const price = BASE[category] + r * 10 + (channel === "Store" ? 15 : 0);
  return { month, region, category, channel, units, price, revenue: units * price };
}))));

export type Dim = "month" | "region" | "category" | "channel";
export type Measure = "revenue" | "units" | "price";
export type Agg = "sum" | "avg" | "count" | "min" | "max";
export type ChartType = "bar" | "line" | "scatter" | "histogram" | "box" | "pie" | "heatmap" | "timeseries";

export const DIMS: Dim[] = ["month", "region", "category", "channel"];
export const MEASURES: Measure[] = ["revenue", "units", "price"];
export const AGGS: Agg[] = ["sum", "avg", "count", "min", "max"];
export const CHART_TYPES: { id: ChartType; label: string }[] = [
  { id: "bar", label: "Bar" }, { id: "line", label: "Line" }, { id: "timeseries", label: "Time series" }, { id: "scatter", label: "Scatter" },
  { id: "histogram", label: "Histogram" }, { id: "box", label: "Box plot" }, { id: "pie", label: "Pie" }, { id: "heatmap", label: "Heatmap" },
];

export interface ChartSpec {
  type: ChartType;
  dim: Dim;
  /** Second dimension for heatmaps and grouped views. */
  dim2: Dim;
  measure: Measure;
  /** Second measure for scatter. */
  measure2: Measure;
  agg: Agg;
  /** Filters: dimension → allowed values. An absent or empty list means all values. */
  filter: Partial<Record<Dim, string[]>>;
  /** Start the value axis at zero (honest) or at the smallest value (can exaggerate differences). */
  zeroBaseline: boolean;
  bins: number;
}

export const DEFAULT_SPEC: ChartSpec = { type: "bar", dim: "region", dim2: "category", measure: "revenue", measure2: "units", agg: "sum", filter: {}, zeroBaseline: true, bins: 8 };

export const dimValues = (d: Dim): string[] => [...new Set(SALES.map((r) => r[d]))].sort();

export function filtered(spec: ChartSpec): SaleRow[] {
  return SALES.filter((r) => (Object.keys(spec.filter) as Dim[]).every((d) => !spec.filter[d]?.length || spec.filter[d]!.includes(r[d])));
}

export function aggregate(values: number[], agg: Agg): number {
  if (!values.length) return 0;
  switch (agg) {
    case "sum": return values.reduce((a, b) => a + b, 0);
    case "avg": return values.reduce((a, b) => a + b, 0) / values.length;
    case "count": return values.length;
    case "min": return Math.min(...values);
    case "max": return Math.max(...values);
  }
}

export interface Point { label: string; value: number; n: number }

export function groupBy(rows: SaleRow[], dim: Dim, measure: Measure, agg: Agg): Point[] {
  const by = new Map<string, number[]>();
  for (const r of rows) by.set(r[dim], [...(by.get(r[dim]) ?? []), r[measure]]);
  return [...by.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([label, v]) => ({ label, value: Math.round(aggregate(v, agg) * 100) / 100, n: v.length }));
}

export function histogram(values: number[], bins: number): { from: number; to: number; count: number }[] {
  if (!values.length) return [];
  const lo = Math.min(...values), hi = Math.max(...values), w = (hi - lo) / bins || 1;
  const out = Array.from({ length: bins }, (_, i) => ({ from: lo + i * w, to: lo + (i + 1) * w, count: 0 }));
  for (const v of values) out[Math.min(bins - 1, Math.floor((v - lo) / w))].count++;
  return out.map((b) => ({ ...b, from: Math.round(b.from * 100) / 100, to: Math.round(b.to * 100) / 100 }));
}

const quantile = (s: number[], q: number) => { const p = (s.length - 1) * q, f = Math.floor(p); return s[f] + (s[Math.min(f + 1, s.length - 1)] - s[f]) * (p - f); };

export interface BoxStats { label: string; min: number; q1: number; median: number; q3: number; max: number; outliers: number[]; n: number }

/** Five-number summary per group; outliers lie beyond 1.5 × IQR from the quartiles (Tukey's rule). */
export function boxStats(rows: SaleRow[], dim: Dim, measure: Measure): BoxStats[] {
  const by = new Map<string, number[]>();
  for (const r of rows) by.set(r[dim], [...(by.get(r[dim]) ?? []), r[measure]]);
  return [...by.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([label, v]) => {
    const s = [...v].sort((a, b) => a - b), q1 = quantile(s, 0.25), q3 = quantile(s, 0.75), iqr = q3 - q1;
    const lo = q1 - 1.5 * iqr, hi = q3 + 1.5 * iqr, inside = s.filter((x) => x >= lo && x <= hi);
    return { label, min: inside[0], q1, median: quantile(s, 0.5), q3, max: inside[inside.length - 1], outliers: s.filter((x) => x < lo || x > hi), n: s.length };
  });
}

export function heatmap(rows: SaleRow[], d1: Dim, d2: Dim, measure: Measure, agg: Agg): { rows: string[]; cols: string[]; cells: number[][] } {
  const rs = [...new Set(rows.map((r) => r[d1]))].sort(), cs = [...new Set(rows.map((r) => r[d2]))].sort();
  return { rows: rs, cols: cs, cells: rs.map((a) => cs.map((b) => Math.round(aggregate(rows.filter((r) => r[d1] === a && r[d2] === b).map((r) => r[measure]), agg) * 100) / 100)) };
}

export interface ChartModel {
  type: ChartType;
  rowCount: number;
  points?: Point[];
  scatter?: { x: number; y: number; label: string }[];
  bins?: ReturnType<typeof histogram>;
  box?: BoxStats[];
  grid?: ReturnType<typeof heatmap>;
}

export function buildChart(spec: ChartSpec): ChartModel {
  const rows = filtered(spec);
  const base: ChartModel = { type: spec.type, rowCount: rows.length };
  switch (spec.type) {
    case "bar": case "line": case "pie": return { ...base, points: groupBy(rows, spec.dim, spec.measure, spec.agg) };
    case "timeseries": return { ...base, points: groupBy(rows, "month", spec.measure, spec.agg) };
    case "scatter": return { ...base, scatter: rows.map((r) => ({ x: r[spec.measure], y: r[spec.measure2], label: `${r.region} ${r.category}` })) };
    case "histogram": return { ...base, bins: histogram(rows.map((r) => r[spec.measure]), spec.bins) };
    case "box": return { ...base, box: boxStats(rows, spec.dim, spec.measure) };
    case "heatmap": return { ...base, grid: heatmap(rows, spec.dim, spec.dim2, spec.measure, spec.agg) };
  }
}

export interface Advice { level: "good" | "warn"; text: string }

/** Rule-based guidance. Each rule names the condition it checks. */
export function adviseChart(spec: ChartSpec, model: ChartModel): Advice[] {
  const out: Advice[] = [];
  const pts = model.points ?? [];
  if (model.rowCount === 0) return [{ level: "warn", text: "The filters leave no rows, so there is nothing to draw." }];
  switch (spec.type) {
    case "bar": out.push({ level: "good", text: "Bars compare amounts across categories. Their length encodes the value, so the axis should start at zero." }); break;
    case "line": out.push({ level: "warn", text: DIM_ORDERED.has(spec.dim) ? "A line joins points in order, which suits an ordered dimension such as month." : `A line implies the order of ${spec.dim} means something (a trend), but ${spec.dim} has no natural order. A bar chart is the honest choice.` }); break;
    case "timeseries": out.push({ level: "good", text: "A time series shows change over time, so the points are joined in date order." }); break;
    case "pie": out.push({ level: pts.length > 5 || pts.some((p) => p.value < 0) ? "warn" : "good", text: pts.length > 5 ? `${pts.length} slices are hard to compare by angle. Use a bar chart.` : pts.some((p) => p.value < 0) ? "A pie cannot show negative values." : "A pie shows parts of a whole. It works with a few slices that add to a meaningful total." });
      if (spec.agg === "avg" || spec.agg === "min" || spec.agg === "max") out.push({ level: "warn", text: `Slices of an ${spec.agg} do not add up to a whole, so the pie is misleading. Use sum or count.` }); break;
    case "scatter": out.push({ level: spec.measure === spec.measure2 ? "warn" : "good", text: spec.measure === spec.measure2 ? "Both axes show the same measure; pick two different measures to look for a relationship." : "A scatter plot shows how two measures move together. A pattern here is a correlation, not proof that one causes the other." }); break;
    case "histogram": out.push({ level: "good", text: "A histogram shows how values are distributed. The shape depends on the bin count, so try a few." }); break;
    case "box": out.push({ level: "good", text: "A box plot summarises a distribution per group: the box is the middle half of values, the line the median, dots are outliers." }); break;
    case "heatmap": out.push({ level: "good", text: "A heatmap compares a measure across two dimensions at once. Darker means a larger value; read exact values from the table." }); break;
  }
  if ((spec.type === "bar" || spec.type === "line" || spec.type === "timeseries") && !spec.zeroBaseline) out.push({ level: "warn", text: "The value axis does not start at zero, which exaggerates differences between bars or points." });
  if (spec.agg === "avg" && (spec.type === "bar" || spec.type === "line")) out.push({ level: "warn", text: "An average hides how many rows each bar covers and how spread out they are. Check the counts or use a box plot." });
  return out;
}

const DIM_ORDERED: ReadonlySet<Dim> = new Set(["month"]);

/** The value axis range for a bar or line chart. Starting above zero is allowed only when the learner turns the zero baseline off. */
export function axisRange(points: Point[], zeroBaseline: boolean): [number, number] {
  const vals = points.map((p) => p.value);
  if (!vals.length) return [0, 1];
  const hi = Math.max(...vals), lo = Math.min(...vals);
  return [zeroBaseline ? Math.min(0, lo) : lo * 0.95, hi * 1.05 || 1];
}
