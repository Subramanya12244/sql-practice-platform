// Writes docs/DAILY_LEARNING_CONTENT_COVERAGE.md from the curriculum and the authored lessons.
//   node scripts/daily-coverage.mjs [output.md]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { curriculum, loadDays } from "./daily-lib.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] ?? path.join(here, "../../docs/DAILY_LEARNING_CONTENT_COVERAGE.md");
const days = loadDays();
const byId = new Map(days.map((d) => [d.id, d]));
const words = (s) => (s ?? "").split(/\s+/).filter(Boolean).length;
const row = (d) => {
  const ex = d.examples;
  const all = [...d.extras.guided, ...d.extras.independent];
  return {
    id: d.id, day: d.meta.day, title: d.meta.title, kind: d.meta.kind,
    theory: words(d.sections["Understand"]),
    run: ex.filter((e) => e.browser).length, local: ex.filter((e) => e.lang === "python" && !e.browser).length, bash: ex.filter((e) => e.lang === "bash").length,
    graded: all.filter((e) => e.kind !== "written").length, written: all.filter((e) => e.kind === "written").length,
    guided: d.extras.guided.length, independent: d.extras.independent.length, checks: d.extras.checks.length,
    links: Object.values(d.extras.links ?? {}).flat().length, env: !!d.extras.environment,
  };
};

const lines = [];
const total = curriculum.days.length;
const missing = curriculum.days.filter((d) => !byId.has(d.id));
lines.push("# Daily Learning content coverage", "", `Generated by \`frontend/scripts/daily-coverage.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`, "");
lines.push("## Summary", "");
lines.push(`- Curriculum entries: ${total} (90 common, 90 Data Analyst, 90 Data Engineer; 180 days on each route).`);
lines.push(`- Lessons authored: ${days.length} of ${total}.`);
lines.push(`- Lessons missing: ${missing.length}${missing.length ? ` (${missing.map((d) => d.id).join(", ")})` : ""}.`);
const rows = days.map(row);
const sum = (k) => rows.reduce((s, r) => s + r[k], 0);
lines.push(`- Runnable examples: ${sum("run")} in browser and tests, ${sum("local")} \`python local\`, ${sum("bash")} \`bash run\` (tests only).`);
lines.push(`- Exercises: ${sum("guided")} guided and ${sum("independent")} independent; ${sum("graded")} auto-graded and ${sum("written")} written (self-assessed).`);
lines.push(`- Knowledge-check questions: ${sum("checks")}. Understand theory words: ${sum("theory").toLocaleString("en")}.`);
lines.push(`- Days with an environment note (software the browser cannot run): ${rows.filter((r) => r.env).length}.`, "");

lines.push("## Coverage by phase", "", "| Phase | Route | Days | Authored | Missing |", "|---|---|---|---|---|");
for (const ph of curriculum.phases) {
  const ds = curriculum.days.filter((d) => d.phase === ph.id);
  const have = ds.filter((d) => byId.has(d.id)).length;
  lines.push(`| ${ph.title} | ${ph.path} | ${ph.firstDay}–${ph.lastDay} | ${have}/${ds.length} | ${ds.length - have} |`);
}

lines.push("", "## Every day", "", "Columns: theory words in Understand; run = examples run in the browser and tests; local = `python local`; bash = `bash run`; graded / written exercises; guided + independent; checks; links to existing DataForge content; env = environment note.", "");
for (const route of ["common", "analyst", "engineer"]) {
  lines.push(`### ${route === "common" ? "Common core (days 1–90)" : route === "analyst" ? "Data Analyst path (days 91–180)" : "Data Engineer path (days 91–180)"}`, "", "| Day | Id | Title | Kind | Theory | Run | Local | Bash | Graded | Written | G+I | Checks | Links | Env |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const d of curriculum.days.filter((x) => x.path === route)) {
    const r = rows.find((x) => x.id === d.id);
    lines.push(r
      ? `| ${d.day} | ${d.id} | ${d.title} | ${d.kind} | ${r.theory} | ${r.run} | ${r.local} | ${r.bash} | ${r.graded} | ${r.written} | ${r.guided}+${r.independent} | ${r.checks} | ${r.links} | ${r.env ? "yes" : ""} |`
      : `| ${d.day} | ${d.id} | ${d.title} | ${d.kind} | missing | | | | | | | | | |`);
  }
  lines.push("");
}

lines.push("## Environment-dependent days", "", "These days include examples or exercises that need software the browser cannot run. Each has an `environment` note in its lesson, and each has a graded alternative that runs in the browser (pure Python, pandas, `sqlite3` or PGlite SQL).", "", "| Id | Title | Packages | Note |", "|---|---|---|---|");
for (const d of days.filter((x) => x.extras.environment)) {
  const e = d.extras.environment;
  lines.push(`| ${d.id} | ${d.meta.title} | ${e.packages.join(", ") || "none"} | ${e.note.replace(/\|/g, "/").replace(/\n/g, " ")} |`);
}

lines.push("", "## Prerequisite sequencing", "", "- Every prerequisite listed in `curriculum.json` exists, is on the same route and comes earlier (checked by `siteDaily.test.ts`).");
lines.push("- Each lesson's `Next-day preparation` names the next day's topic (checked by `siteDaily.test.ts`).");
lines.push("- No paragraph of theory is repeated across days (checked by `siteDaily.test.ts`).", "");
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${days.length}/${total} lessons`);
